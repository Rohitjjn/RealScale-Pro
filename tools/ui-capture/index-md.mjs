#!/usr/bin/env node
/**
 * Writes docs/ui-reference/screens/INDEX.md from the captured folders + scenarios.mjs.
 * Every row ties one reference PNG pair to the Compose test that must reproduce it. The Compose
 * screenshot tests use the same `NN-name` file stem, so tools/visual-diff compares them 1:1.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const screens = path.join(repo, 'docs/ui-reference/screens');

const ROUTE = [
  ['onboarding-splash', 'Onboarding · phase=splash', 'OnboardingSplashTest'],
  ['guide-', 'Onboarding · phase=guide', 'OnboardingGuideTest'],
  ['permission-', 'Onboarding · phase=perm-photos / perm-notif', 'OnboardingPrimerTest'],
  ['device-check', 'Onboarding · phase=device', 'OnboardingDeviceCheckTest'],
  ['setup-', 'Onboarding · phase=setup', 'OnboardingSetupTest'],
  ['home-', 'Home', 'HomeScreenTest'],
  ['gallery-', 'Gallery', 'GalleryScreenTest'],
  ['viewer-', 'Viewer', 'ViewerScreenTest'],
  ['config-', 'Config', 'ConfigScreenTest'],
  ['processing-', 'Processing', 'ProcessingScreenTest'],
  ['job-strip', 'Shell · JobStrip', 'JobStripTest'],
  ['result', 'Result', 'ResultScreenTest'],
  ['upscales-', 'My Upscales', 'UpscalesScreenTest'],
  ['models-', 'Model Manager', 'ModelsScreenTest'],
  ['settings', 'Settings', 'SettingsScreenTest'],
  ['help-', 'Help', 'HelpScreenTest'],
  ['about', 'About', 'AboutScreenTest'],
  ['toast-', 'Toast (over any screen)', 'ToastTest'],
];

const routeOf = (name) => ROUTE.find(([k]) => name.includes(k)) ?? ['', 'Component gallery', 'ComponentGalleryTest'];

const folders = ['light', 'dark'].filter((d) => fs.existsSync(path.join(screens, d)));
const stems = [...new Set(folders.flatMap((d) => fs.readdirSync(path.join(screens, d)).filter((f) => f.endsWith('.png')).map((f) => f.replace(/\.png$/, ''))))].sort();

const missing = (stem) => folders.filter((d) => !fs.existsSync(path.join(screens, d, `${stem}.png`)));

const rows = stems.map((stem) => {
  const name = stem.replace(/^\d+-/, '');
  const [, route, test] = routeOf(name);
  const gap = missing(stem);
  const layout = folders.some((d) => fs.existsSync(path.join(screens, d, `${stem}.layout.json`)));
  return `| \`${stem}\` | ${route} | ${test} | ${layout ? '✓' : '—'} | ${gap.length ? `missing in ${gap.join(', ')}` : 'both themes'} |`;
});

const md = `# Reference screens (captured from the React prototype)

Generated by \`tools/ui-capture\` — regenerate with \`npm run capture && node index-md.mjs\`.
Viewport 400 × 860 CSS px @ DSF 2 (800 × 1720 px PNGs), \`prefers-reduced-motion: reduce\`,
one folder per theme. Every state was reached through the prototype's own controls; no React
state was poked from the outside.

Each state has two files per theme:

- \`NN-name.png\` — the screenshot.
- \`NN-name.layout.json\` — a nested layout spec: for every visible node its bounding box relative
  to the viewport, tag/role/aria-label/own text, and the computed styles that matter
  (font family/size/weight/line-height/letter-spacing, colours, borders, radius, padding, margin,
  gap, shadow, opacity, transform, animation name/duration/easing, display/flex/alignment).

The Compose screenshot tests use the same \`NN-name\` stem, so \`tools/visual-diff\` pairs
reference ↔ render automatically. "Compose test" is the test class that must reproduce it.

| Reference | Route / state | Compose test | Layout spec | Coverage |
| --- | --- | --- | --- | --- |
${rows.join('\n')}
`;

fs.writeFileSync(path.join(screens, 'INDEX.md'), md);
console.log(`INDEX.md: ${rows.length} states, themes: ${folders.join(' + ')}`);
