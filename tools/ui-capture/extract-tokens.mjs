#!/usr/bin/env node
/**
 * Reads the prototype's CSS and the captured layout specs and emits Compose-ready design tokens:
 *
 *   docs/ui-reference/tokens.json   colours (light/dark), radii, shadow, easing, keyframes,
 *                                   observed type scale (family/size/weight/tracking/line-height)
 *   docs/ui-reference/TOKENS.md     the same, readable, with the Compose mapping rule used in the app
 *
 * 1rem = 16dp and 1px = 1dp, so a rem/px value here is already a dp/sp value in Compose.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const proto = path.join(repo, 'docs/ui-reference/prototype');
const screens = path.join(repo, 'docs/ui-reference/screens');
const css = fs.readFileSync(path.join(proto, 'src/index.css'), 'utf8');

const block = (selector) => {
  const at = css.indexOf(selector);
  if (at < 0) throw new Error(`selector not found: ${selector}`);
  const open = css.indexOf('{', at);
  const close = css.indexOf('\n}', open);
  return css.slice(open + 1, close);
};

const decls = (body) =>
  Object.fromEntries(
    [...body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)].map(([, k, v]) => [k, v.trim()]),
  );

const light = decls(block(':root {'));
const dark = decls(block('[data-theme="dark"] {'));

/** Colour tokens that change between themes (everything the Compose theme must model). */
const themed = Object.keys(light).filter((k) => k.startsWith('c-') && dark[k]);
const colors = themed.map((k) => ({ token: k.slice(2), light: light[k], dark: dark[k] }));

/** Fixed colours from the Tailwind @theme block (primary / accents). */
const theme = decls(block('@theme inline {'));
const fixedColors = ['primary', 'primary-active', 'on-primary', 'teal', 'amber', 'on-accent', 'success', 'warning', 'on-dark', 'on-dark-soft']
  .filter((k) => theme[`color-${k}`])
  .map((k) => ({ token: k, value: theme[`color-${k}`] }));

const radii = Object.entries(theme)
  .filter(([k]) => k.startsWith('radius-'))
  .map(([k, v]) => ({ token: k.slice(7), value: v }));

const keyframes = [...css.matchAll(/@keyframes ([a-z-]+) \{([\s\S]*?)\n\}/g)].map(([, name, body]) => ({
  name,
  body: body
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .join(' '),
}));

const utilities = [...css.matchAll(/@utility anim-([a-z-]+) \{ animation: ([^;]+); \}/g)].map(([, name, value]) => ({ name, value }));
const transitions = {
  spring: light['spring'],
  shadow: theme['shadow-soft'],
  // Named durations that appear in the components (Tailwind classes) rather than in CSS variables.
  observed: ['duration-150', 'duration-200', 'duration-300', 'duration-500', 'duration-[900ms]', 'duration-2000'],
};

/* ---------- observed type scale ---------- */
const families = new Map();
const sizes = new Map();
for (const dir of ['light', 'dark']) {
  const folder = path.join(screens, dir);
  if (!fs.existsSync(folder)) continue;
  for (const f of fs.readdirSync(folder).filter((x) => x.endsWith('.layout.json'))) {
    const { tree } = JSON.parse(fs.readFileSync(path.join(folder, f), 'utf8'));
    const walk = (node) => {
      const s = node.s;
      if (node.text && s?.fontSize) {
        const fam = (s.fontFamily ?? '').split(',')[0].replace(/["']/g, '').trim();
        families.set(fam, (families.get(fam) ?? 0) + 1);
        const key = `${s.fontSize} | w${s.fontWeight ?? '400'} | ls ${s.letterSpacing ?? 'normal'} | lh ${s.lineHeight ?? 'normal'}`;
        const entry = sizes.get(key) ?? { key, family: fam, count: 0, sample: node.text.slice(0, 40) };
        entry.count += 1;
        sizes.set(key, entry);
      }
      (node.k ?? []).forEach(walk);
    };
    walk(tree);
  }
}

const typeScale = [...sizes.values()]
  .sort((a, b) => parseFloat(a.key) - parseFloat(b.key) || b.count - a.count)
  .slice(0, 120);

const out = {
  generatedFrom: 'docs/ui-reference/prototype/src/index.css + docs/ui-reference/screens/*/*.layout.json',
  conversion: { '1rem': '16dp', '1px': '1dp', 'letterSpacing(em)': 'value * fontSize in sp', weights: { light: 300, normal: 400, medium: 500, semibold: 600, bold: 700 } },
  fonts: Object.fromEntries(families),
  colors,
  fixedColors,
  radii,
  motion: { spring: transitions.spring, shadow: transitions.shadow, keyframes, utilities },
  typeScale,
};

fs.writeFileSync(path.join(repo, 'docs/ui-reference/tokens.json'), JSON.stringify(out, null, 2));

const md = [
  '# Design tokens (extracted from the prototype CSS)',
  '',
  'Generated by `tools/ui-capture/extract-tokens.mjs` — do not edit by hand.',
  '',
  '## Conversion rules used in Compose',
  '',
  '- `1rem = 16dp`, `1px = 1dp` (so every value below is already a dp/sp value).',
  '- `letter-spacing: -0.02em` → `sp = -0.02 × fontSize`; Compose `TextStyle(letterSpacing = (em * size).sp)`.',
  '- Fonts: display = Cormorant Garamond 500/600, body = Inter Variable, numbers = JetBrains Mono Variable.',
  '- Only one shadow exists in the system: `0 1px 3px rgba(20,20,19,0.08)`.',
  '',
  '## Colours (light / dark)',
  '',
  '| Token | Light | Dark |',
  '| --- | --- | --- |',
  ...colors.map((c) => `| \`${c.token}\` | \`${c.light}\` | \`${c.dark}\` |`),
  '',
  '## Fixed colours',
  '',
  '| Token | Value |',
  '| --- | --- |',
  ...fixedColors.map((c) => `| \`${c.token}\` | \`${c.value}\` |`),
  '',
  '## Radius scale',
  '',
  '| Token | Value |',
  '| --- | --- |',
  ...radii.map((r) => `| \`${r.token}\` | ${r.value} |`),
  '',
  '## Motion',
  '',
  `Spring easing: \`${transitions.spring}\` → \`CubicBezierEasing(0.22f, 1f, 0.36f, 1f)\`.`,
  '',
  '| Utility | Animation |',
  '| --- | --- |',
  ...utilities.map((u) => `| \`anim-${u.name}\` | \`${u.value}\` |`),
  '',
  '| Keyframes | Definition |',
  '| --- | --- |',
  ...keyframes.map((k) => `| \`${k.name}\` | \`${k.body}\` |`),
  '',
  '## Observed type styles',
  '',
  '| Family | Size | Weight | Tracking | Line-height | Used | Sample |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...typeScale.map((t) => `| ${t.family} | ${t.key.split(' | ')[0]} | ${t.key.split(' | ')[1]} | ${t.key.split(' | ')[2]} | ${t.key.split(' | ')[3]} | ${t.count} | ${t.sample.replace(/\|/g, '\\|')} |`),
  '',
].join('\n');

fs.writeFileSync(path.join(repo, 'docs/ui-reference/TOKENS.md'), md);
console.log(`tokens: ${colors.length} themed colours, ${radii.length} radii, ${keyframes.length} keyframes, ${typeScale.length} type styles`);
